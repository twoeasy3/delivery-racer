export const kindOf = (car) => KINDS[car.id] || KINDS[car.model || car.id] || 'car';

// a shape: { scale, centre, yaw, inset, ... }. `centre` is the shape's centre with its base on the HIGHEST point of the surface under it;
// `inset` (m, 0 on a flat surface) is how far it is SUNK so that its base meets the lowest point too (a curved roof, a crowned deck: the
// owner, 15-Oct): the place to put a prop is centre lowered by inset (fitProp does it)
const toShape = (slot, shape, e, inset) => {
  if (!e) return null;
  const [s, x, y, z, yaw] = e;
  const c = PROP_BOUNDS[slot];
  return shape === 'box'
    ? { scale: s, centre: [x, y, z], yaw: yaw || 0, inset, size: c.box.map(v => v * s) }
    : { scale: s, centre: [x, y, z], yaw: yaw || 0, inset, radius: c.cylinder.radius * s, height: c.cylinder.height * s, axis: c.cylinder.axis };
};
const toSlot = (slot, e) => {
  if (!e || e.no) return { supported: false, reason: e ? e.no : 'no entry', box: null, cylinder: null, existing: !!(e && e.existing) }; // (existing on an unsupported slot: the car's own prop is there, tagged, but there is no place for another)
  const inset = Array.isArray(e.inset) ? e.inset : [0, 0];
  return { supported: true, reason: null, box: toShape(slot, 'box', e.box, inset[0] || 0), cylinder: toShape(slot, 'cyl', e.cyl, inset[1] || 0), from: e.from || null, limit: e.lim || null, existing: !!e.existing, confidence: e.conf || 'measured' };
};
const entryOf = (carId) => {
  const base = PROP_TABLE[carId] || {};
  const hand = HAND[carId] || {};
  const out = {};
  for (const slot of SLOTS) out[slot] = slot in hand ? { ...hand[slot], conf: 'hand' } : base[slot];
  return out;
};
// the three slots of a car: { roof, cargo, wing }, each { supported, reason, box, cylinder, from, limit, existing, confidence }
//   box: { scale, centre, yaw, size }   cylinder: { scale, centre, yaw, radius, height, axis }   (null when unsupported)
export const propSlots = (carId) => {
  const e = entryOf(carId);
  return { roof: toSlot('roof', e.roof), cargo: toSlot('cargo', e.cargo), wing: toSlot('wing', e.wing) };
};
export const propSupported = (carId, slot) => propSlots(carId)[slot]?.supported === true;
// the transform for a prop MODELLED TO THE CANONICAL BOUNDS of a slot (fits inside PROP_BOUNDS[slot].box or .cylinder at scale 1,
// centred on the origin): { position: [x, y, z], rotationY: yaw, scale: s } to set on the prop (prop.position.set(...),
// prop.rotation.y = rotationY, prop.scale.setScalar(scale)), as a child of the car's model. null when the slot is unsupported.
export const fitProp = (carId, slot, shape = 'box') => {
  const s = propSlots(carId)[slot];
  if (!s || !s.supported) return null;
  const sh = shape === 'cylinder' || shape === 'cyl' ? s.cylinder : s.box;
  const position = sh.centre.slice();
  position[1] -= sh.inset || 0; // (sunk into a curved surface so the base has several points of contact)
  return { position, rotationY: sh.yaw, scale: sh.scale, inset: sh.inset || 0, bounds: PROP_BOUNDS[slot][shape === 'box' ? 'box' : 'cylinder'] };
};
export const propTableStats = () => {
  const out = { cars: Object.keys(PROP_TABLE).length, hand: Object.keys(HAND).length, slices: SLICES.map(s => s.file) };
  for (const slot of SLOTS) out[slot] = Object.values(PROP_TABLE).filter(e => e[slot] && !e[slot].no).length;
  return out;
};
